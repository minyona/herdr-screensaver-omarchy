#!/usr/bin/env python3
"""CREDITS.md from the content sources only, and the check that it says nothing else.

  python3 -I tests/credits_check.py           check CREDITS.md == the generated text, then the rules
  python3 -I tests/credits_check.py --write   (re)write CREDITS.md

Sources: content.json (the shipped eggs: their ids, categories and the T thank-you lines) and
tests/credits/v2-sources.json (a verbatim copy of the source app's content/v2-sources.json at 39b6acc: the
X post each original v2 egg paraphrases). Rules: every URL and @handle in CREDITS.md is in the sources;
every source URL of a shipped egg is credited; every name in the thank-you section appears in a shipped line.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "content.json")
V2 = os.path.join(ROOT, "tests", "credits", "v2-sources.json")
OUT = os.path.join(ROOT, "CREDITS.md")
URL = re.compile(r"https://x\.com/([A-Za-z0-9_]+)/status/[0-9]+")
NOD_CATEGORIES = ("poteto", "doomers", "handcoders", "dhh_37signals_omarchy", "rails_doctrine")


def load():
    with open(CONTENT, encoding="utf-8") as f:
        content = json.load(f)
    with open(V2, encoding="utf-8") as f:
        v2 = json.load(f)["sources"]
    return content, v2


def generate(content, v2):
    eggs = content["eggs"]
    shipped = {e["id"] for e in eggs}
    labels = {}
    for e in eggs:
        labels.setdefault(e["category"], e.get("category_label") or e["category"])
    counts = {}
    for e in eggs:
        counts[e["category"]] = counts.get(e["category"], 0) + 1
    thanks = [e for e in eggs if e.get("source") == "T"]

    posts = {}   # url -> ids
    for eid, src in v2.items():
        m = URL.search(src)
        if m and eid in shipped:
            posts.setdefault(m.group(0), []).append(eid)

    L = ["# Credits", "",
         "Generated by `python3 tests/credits_check.py --write` from `content.json` and the source list of the",
         "original eggs (`tests/credits/v2-sources.json`). Nothing here goes beyond what those sources say.", "",
         "## Omarchy", "",
         "`bin/herdr-screensaver-launch` is derived from Omarchy's `omarchy-launch-screensaver`, and `lib/session.sh`",
         "follows Omarchy's `omarchy-screensaver`. Omarchy is by David Heinemeier Hansson, MIT licensed; the notice",
         "is in [THIRD_PARTY_NOTICES.md](THIRD_PARTY_NOTICES.md).", "",
         "## Thank-you lines", "",
         "%d eggs thank Alex Epstein for the words \"amplified intelligence\". They ship word for word:" % len(thanks), ""]
    for e in thanks:
        L.append("- %s: %s" % (e["id"], e["text"]))
    L += ["", "## Posts the original eggs paraphrase", "",
          "%d of the original eggs paraphrase a post on X. The others are genre tropes or original" % sum(len(v) for v in posts.values()),
          "riffs. Each post, its author's handle and the eggs that paraphrase it:", "",
          "| Handle | Post | Eggs |", "|---|---|---|"]
    for url in sorted(posts, key=lambda u: (URL.match(u).group(1).lower(), u)):
        ids = sorted(posts[url], key=lambda i: (i[0], int(i[1:])))
        L.append("| @%s | %s | %s |" % (URL.match(url).group(1), url, ", ".join(ids)))
    L += ["", "## Nods", "",
          "These categories of eggs are nods, named as the content names them; the lines are the screensaver's own:", ""]
    for cat in NOD_CATEGORIES:
        if cat in labels:
            L.append("- %s (%d eggs)" % (labels[cat], counts[cat]))
    L.append("")
    return "\n".join(L)


def check(text, content, v2):
    errs = []
    shipped = {e["id"] for e in content["eggs"]}
    src_urls = {URL.search(s).group(0) for s in v2.values() if URL.search(s)}
    src_handles = {URL.search(s).group(1) for s in v2.values() if URL.search(s)}
    for url in {m.group(0) for m in URL.finditer(text)}:
        if url not in src_urls:
            errs.append("URL not in the sources: " + url)
    for h in re.findall(r"@([A-Za-z0-9_]+)", text):
        if h not in src_handles:
            errs.append("handle not in the sources: @" + h)
    for eid, s in v2.items():
        m = URL.search(s)
        if m and eid in shipped and m.group(0) not in text:
            errs.append("shipped egg %s: source not credited: %s" % (eid, m.group(0)))
    lines = " ".join(e["text"] for e in content["eggs"] if e.get("source") == "T")
    if "Alex Epstein" not in lines:
        errs.append("Alex Epstein is credited but no shipped line names him")
    if "http" in re.sub(URL, "", text):
        errs.append("a link that is not a source post")
    return errs


def main(argv):
    content, v2 = load()
    text = generate(content, v2)
    if argv[1:] == ["--write"]:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote CREDITS.md")
    with open(OUT, encoding="utf-8") as f:
        have = f.read()
    errs = [] if have == text else ["CREDITS.md differs from the generated text (run with --write)"]
    errs += check(have, content, v2)
    for e in errs:
        print("credits_check: FAIL: " + e)
    if not errs:
        print("credits_check: ok (%d post links, all from the sources)" % len(set(m.group(0) for m in URL.finditer(have))))
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
